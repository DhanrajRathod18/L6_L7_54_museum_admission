from hypothesis import given, strategies as st
import pytest

from museum_admission_parser import (
    format_visitor_name,
    parse_group_ages,
    parse_visit_date,
)


@given(st.text())
def test_format_visitor_name_formats_random_strings_or_rejects_blank(value):
    """Random nonblank names are formatted; blank names raise ValueError."""
    parts = value.split()
    if not parts:
        with pytest.raises(ValueError):
            format_visitor_name(value)
    else:
        expected = parts[-1].title()
        if len(parts) > 1:
            expected += ', ' + ' '.join(parts[:-1]).title()
        assert format_visitor_name(value) == expected


@given(st.sampled_from(["", " ", "\t", "\n", "   "]))
def test_format_visitor_name_rejects_empty_and_whitespace_names(value):
    """Empty and whitespace-only names are invalid."""
    with pytest.raises(ValueError):
        format_visitor_name(value)


@given(st.one_of(st.none(), st.integers(), st.floats(), st.lists(st.text()), st.booleans()))
def test_format_visitor_name_rejects_unexpected_types(value):
    """Names must be strings, not None, numbers, lists, or booleans."""
    with pytest.raises(ValueError):
        format_visitor_name(value)


@given(st.text())
def test_parse_group_ages_parses_random_digits_or_rejects_invalid_text(value):
    """Random digit groups parse; other text is rejected with ValueError."""
    parts = value.split()
    if parts and all(part.isdecimal() for part in parts):
        assert parse_group_ages(value) == [int(part) for part in parts]
    else:
        with pytest.raises(ValueError):
            parse_group_ages(value)


@given(st.sampled_from(["", " ", "\t", "\n", "   "]))
def test_parse_group_ages_rejects_empty_and_whitespace_input(value):
    """A group must contain at least one age."""
    with pytest.raises(ValueError):
        parse_group_ages(value)


@given(st.one_of(st.none(), st.integers(), st.floats(), st.lists(st.text()), st.booleans()))
def test_parse_group_ages_rejects_unexpected_types(value):
    """Age input must be a string."""
    with pytest.raises(ValueError):
        parse_group_ages(value)


@given(st.sampled_from(["abc", "12.5", "-", "1 x"]))
def test_parse_group_ages_rejects_invalid_age_values(value):
    """Every age must be a non-negative whole number."""
    with pytest.raises(ValueError):
        parse_group_ages(value)


@given(st.sampled_from(["-1", "12 -3"]))
def test_parse_group_ages_rejects_negative_ages(value):
    """Negative ages are invalid."""
    with pytest.raises(ValueError):
        parse_group_ages(value)


@given(st.integers(min_value=0, max_value=120))
def test_parse_group_ages_accepts_zero_and_other_boundary_ages(value):
    """Zero and other non-negative whole-number ages remain valid."""
    assert parse_group_ages(str(value)) == [value]


@given(st.dates())
def test_parse_visit_date_parses_random_valid_dates(value):
    """Every valid date generated by Hypothesis is parsed into integer parts."""
    assert parse_visit_date(value.isoformat()) == (
        value.year,
        value.month,
        value.day,
    )


