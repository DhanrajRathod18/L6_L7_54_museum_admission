@given(st.sampled_from(["not-a-date", "2026/01/01", "2026-1-2", "2026-13-01"]))
def test_parse_visit_date_rejects_malformed_dates(value):
    """Dates must use the exact YYYY-MM-DD format and valid ranges."""
    with pytest.raises(ValueError):
        parse_visit_date(value)


@given(st.sampled_from(["2026-02-30", "2026-04-31", "2026-02-29"]))
def test_parse_visit_date_rejects_impossible_dates(value):
    """Dates that do not exist on the calendar are rejected."""
    with pytest.raises(ValueError):
        parse_visit_date(value)


@given(st.sampled_from(["0001-01-01", "2024-02-29", "9999-12-31"]))
def test_parse_visit_date_accepts_boundary_valid_dates(value):
    """Valid dates at the calendar boundaries remain supported."""
    year, month, day = map(int, value.split('-'))
    assert parse_visit_date(value) == (year, month, day)
